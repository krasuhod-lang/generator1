export const YANDEX_REGIONS_RU = YANDEX_REGIONS;

const REGION_BY_CODE = new Map(YANDEX_REGIONS.map((region) => [String(region.code), region]));
const SEARCH_NORMALIZE_RE = /[Ёё]/g;

function normalizeSearchValue(value) {
  return String(value || '').toLocaleLowerCase('ru-RU').replace(SEARCH_NORMALIZE_RE, 'е').trim();
}

export function findRegionByCode(code) {
  return REGION_BY_CODE.get(String(code)) || null;
}

export function regionParentLabel(region) {
  if (!region?.parentCode) return "";
  return findRegionByCode(region.parentCode)?.name || "";
}

export function searchRegions(query, limit = 100) {
  const q = normalizeSearchValue(query);
  const rows = q
    ? YANDEX_REGIONS.filter((region) => normalizeSearchValue(region.name).includes(q) || String(region.code).includes(q))
    : YANDEX_REGIONS;
  return rows.slice(0, Math.max(1, Number(limit) || 100));
}
